def fix_text(s):
    if not s:
        return ""
    s = str(s)
    for a, b in {
        "深?浅色": "深色/浅色",
        "自?/手动": "自动/手动",
        "启?/禁用": "启用/禁用",
        "近七?/近一月": "近七日/近一月",
        "按日?/月": "按日/周/月",
        "最?/4小时": "最近24小时",
        "按全?/成功": "按全部/成功",
        "开始时?/结束": "开始时间/结束",
        "列?/图表": "列表/图表",
        "公有?/私有": "公有云/私有",
    }.items():
        s = s.replace(a, b)
    return s


# 原子系统名称映射为对外系统名称
SYS_NAME_MAP = {
    "inCloud云平台": "超融合管理系统",
    "道路停车值守平台": "视频管理平台",
}


def build_rows(src_rows):
    out = []
    seq = 1
    missing = []
    for r in src_rows:
        oid = r[0]
        if oid not in ATOMIC:
            missing.append(oid)
            continue
        # 子系统=原模块；模块=原功能点名称（按用户示例）
        sub_sys = fix_text(r[3])  # 原模块 -> 子系统
        module = fix_text(r[5])   # 原功能点名称 -> 模块
        if not sub_sys:
            sub_sys = fix_text(r[2])
        # 系统名称：inCloud/道路停车值守 按要求更名，其余保持物联网中台
        orig_sub = fix_text(r[2])
        sys_name = SYS_NAME_MAP.get(orig_sub, fix_text(r[1]))
        for name, desc, days in ATOMIC[oid]:
            out.append({
                "序号": seq,
                "原序号": oid,
                "系统名称": sys_name,
                "子系统": sub_sys,
                "模块": module,
                "功能点名称": name,
                "功能点描述": desc,
                "工作量（人天）": days,
                "原功能点名称": module,
                "原功能点描述": fix_text(r[6]),
                "原工作量（人天）": r[7],
            })
            seq += 1
    if missing:
        raise RuntimeError(f"未配置拆解的原序号: {missing}")
    return out


